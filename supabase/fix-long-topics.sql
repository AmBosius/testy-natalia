-- ============================================================
-- Разовый фикс: у части импортированных тестов тема — это
-- несколько склеенных пунктов кодификатора ФИПИ через " | ".
-- Оставляем только первый пункт.
-- ============================================================

update tests
set topic = split_part(topic, ' | ', 1)
where topic like '%| %';
